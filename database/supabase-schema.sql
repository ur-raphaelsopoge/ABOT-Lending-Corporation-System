create extension if not exists pgcrypto with schema extensions;

drop table if exists
    public.audit_ledgers,
    public.receipt_logs,
    public.capital_shares,
    public.loan_applications,
    public.loans,
    public.password_reset_tokens,
    public.admins,
    public.users
cascade;

drop sequence if exists public.borrower_id_seq;
drop sequence if exists public.loan_application_seq;

create sequence public.borrower_id_seq start with 1 increment by 1;
create sequence public.loan_application_seq start with 1 increment by 1;

create table public.users (
    id bigint generated by default as identity primary key,
    borrower_id varchar(20) not null
        default ('BRW-' || lpad(nextval('public.borrower_id_seq')::text, 5, '0')),
    name varchar(150) not null,
    date_of_birth date not null,
    phone_number varchar(20) not null,
    email varchar(255) not null,
    address text not null,
    id_type varchar(30) not null
        check (id_type in ('philsys', 'drivers_license', 'passport', 'umid', 'sss', 'prc', 'postal')),
    id_number varchar(60) not null,
    employment_status varchar(30) not null
        check (employment_status in ('employed', 'self_employed', 'business_owner', 'unemployed', 'retired')),
    monthly_income numeric(12, 2) not null default 0 check (monthly_income >= 0),
    emergency_contact_name varchar(150) not null,
    emergency_contact_relationship varchar(60) not null,
    emergency_contact_phone varchar(20) not null,
    loan_type varchar(20) not null
        check (loan_type in ('personal', 'business', 'emergency')),
    password varchar(255) not null,
    remember_token varchar(100),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint users_borrower_id_unique unique (borrower_id),
    constraint users_email_unique unique (email),
    constraint users_id_document_unique unique (id_type, id_number)
);

create index users_name_idx on public.users (name);
create index users_created_at_idx on public.users (created_at desc);

create table public.admins (
    id bigint generated by default as identity primary key,
    name varchar(100) not null,
    username varchar(255) not null,
    password varchar(255) not null,
    remember_token varchar(100),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint admins_username_unique unique (username)
);

create table public.password_reset_tokens (
    email varchar(255) primary key,
    token varchar(255) not null,
    created_at timestamptz
);

create table public.loan_applications (
    id bigint generated by default as identity primary key,
    application_number varchar(20) not null
        default ('LA-' || lpad(nextval('public.loan_application_seq')::text, 6, '0')),
    user_id bigint not null references public.users (id) on delete restrict,
    loan_type varchar(20) not null
        check (loan_type in ('personal', 'business', 'emergency')),
    amount numeric(12, 2) not null check (amount >= 1000 and amount <= 50000),
    term_months smallint not null default 6 check (term_months between 1 and 36),
    purpose varchar(255) not null,
    status varchar(20) not null default 'pending'
        check (status in ('pending', 'approved', 'rejected')),
    admin_remarks text,
    reviewed_by bigint references public.admins (id) on delete set null,
    reviewed_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint loan_applications_number_unique unique (application_number)
);

create index loan_applications_user_id_idx on public.loan_applications (user_id);
create index loan_applications_status_idx on public.loan_applications (status);
create index loan_applications_created_at_idx on public.loan_applications (created_at desc);

create table public.capital_shares (
    id bigint generated by default as identity primary key,
    member_id bigint not null references public.users (id) on delete restrict,
    amount numeric(12, 2) not null check (amount > 0),
    share_date date not null default current_date,
    notes text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index capital_shares_member_id_idx on public.capital_shares (member_id);
create index capital_shares_share_date_idx on public.capital_shares (share_date desc);

create table public.receipt_logs (
    id bigint generated by default as identity primary key,
    member_id bigint not null references public.users (id) on delete restrict,
    receipt_number varchar(40) not null,
    amount numeric(12, 2) not null check (amount > 0),
    payment_method varchar(30) not null default 'cash'
        check (payment_method in ('cash', 'gcash', 'bank_transfer', 'check')),
    received_at timestamptz not null default now(),
    notes text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint receipt_logs_receipt_number_unique unique (receipt_number)
);

create index receipt_logs_member_id_idx on public.receipt_logs (member_id);
create index receipt_logs_received_at_idx on public.receipt_logs (received_at desc);

create table public.audit_ledgers (
    id bigint generated by default as identity primary key,
    user_id bigint references public.users (id) on delete set null,
    admin_id bigint references public.admins (id) on delete set null,
    action varchar(60) not null,
    description text not null default '',
    created_at timestamptz not null default now()
);

create index audit_ledgers_user_id_idx on public.audit_ledgers (user_id);
create index audit_ledgers_admin_id_idx on public.audit_ledgers (admin_id);
create index audit_ledgers_created_at_idx on public.audit_ledgers (created_at desc);
create index audit_ledgers_action_idx on public.audit_ledgers (action);

